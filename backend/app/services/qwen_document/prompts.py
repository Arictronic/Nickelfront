from __future__ import annotations

ARTICLE_MARKDOWN_IMAGE_REGENERATION_PROMPT_VERSION = "article_markdown_image_regeneration_v1"


def build_article_markdown_image_regeneration_prompt(
    *,
    paper_title: str,
    page_number: int,
    page_start: int | None,
    page_end: int | None,
) -> str:
    page_label = str(page_number)
    if page_start and page_end and page_start != page_end:
        page_label = f"{page_number} из диапазона {page_start}-{page_end}"
    return (
        "Ты — система восстановления научного текста из изображения/PDF-страницы.\n\n"
        "К тебе прикреплена одна страница научной статьи или патента в виде изображения. "
        "Нужно восстановить содержимое только этой видимой страницы в чистый Markdown.\n\n"
        "КРИТИЧЕСКИ ВАЖНО:\n"
        "- Верни только Markdown.\n"
        "- Не переводи текст.\n"
        "- Не пересказывай и не сокращай.\n"
        "- Не добавляй текста, которого нет на странице.\n"
        "- Не продолжай документ за пределами видимой страницы.\n"
        "- Если страница начинается или заканчивается на середине предложения, сохрани только видимый фрагмент без дописывания.\n"
        "- Сохраняй порядок чтения сверху вниз, слева направо; для двух колонок сначала левая колонка, затем правая.\n"
        "- Сохраняй заголовки, абзацы, списки, таблицы, подписи рисунков и формулы.\n"
        "- Формулы восстанавливай максимально полно в LaTeX.\n"
        "- Если формула имеет номер, сохраняй номер через \\tag{...}.\n"
        "- Недопустимо возвращать пустую формулу вида $$ \\tag{18a} $$.\n"
        "- Если формулу невозможно прочитать, напиши [FORMULA_UNREADABLE tag=18a] вместо пустого блока $$ \\tag{18a} $$.\n"
        "- Не создавай пустые заголовки вида #.\n"
        "- Не создавай служебные маркеры вроде [Formula candidate], [Table candidate], cid:123, <latexit>.\n"
        "- Если таблица повреждена или плохо читается, восстанови только видимые значения; не выдумывай недостающие ячейки.\n"
        "- Не возвращай JSON, YAML, XML, HTML-страницу, debug-логи или комментарии.\n"
        "- Не оборачивай ответ в ```markdown, ```md, ```text или любые другие fenced code blocks.\n\n"
        f"Название статьи: {paper_title or 'без названия'}\n"
        f"Страница: {page_label}\n\n"
        "Ответ: только чистый Markdown видимой страницы."
    )


def build_article_translation_prompt(
    *,
    target_language_code: str,
    target_language_name: str,
    paper_title: str,
    page_start: int | None,
    page_end: int | None,
) -> str:
    page_label = "не указан"
    if page_start and page_end:
        page_label = str(page_start) if page_start == page_end else f"{page_start}-{page_end}"
    return (
        "Ты — профессиональный переводчик научных статей, патентов и технических PDF-документов "
        "по материаловедению, никелевым сплавам, superalloys и heat resistant alloys.\n\n"
        "К тебе прикреплён Markdown-файл одной страницы или одной части статьи. "
        f"Нужно перевести содержимое этого файла на язык: {target_language_name} ({target_language_code}).\n\n"
        "КРИТИЧЕСКИ ВАЖНО ПРО ФОРМАТ ОТВЕТА:\n"
        "- Верни только содержимое переведённого Markdown-документа.\n"
        "- Не оборачивай ответ в ```markdown, ```md, ```text или любые другие fenced code blocks.\n"
        "- Не пиши фразы вроде «Вот перевод», «Перевод:», «Translated Markdown», «Ответ:».\n"
        "- Не добавляй новый заголовок страницы/перевода, если такого заголовка нет в исходном файле.\n"
        "- Markdown — это формат результата, а не текстовая обёртка вокруг результата.\n"
        "- Не возвращай JSON, YAML, HTML-страницу, XML, debug-логи, системные сообщения или коды ошибок.\n"
        "- Если во входном файле есть служебные маркеры парсера, не переводи их как обычный текст — удали только сами маркеры.\n\n"
        "Правила перевода:\n"
        "1. Переводи только текст из прикреплённого Markdown-файла.\n"
        "2. Не добавляй факты, которых нет в исходном тексте.\n"
        "3. Не удаляй научные данные, числа, единицы измерения, формулы, таблицы, ссылки, обозначения сплавов и химические символы.\n"
        "4. Сохраняй полезную структуру Markdown: заголовки, абзацы, списки, таблицы, формулы и подписи.\n"
        "5. Формулы, химические обозначения, марки сплавов, DOI, URL, номера патентов и библиографические ссылки не переводи, если перевод может исказить смысл.\n"
        "6. Термины переводи научно корректно и максимально близко к исходному смыслу. Например, \"solution treatment\" переводи как \"растворяющая обработка\" или \"обработка на твёрдый раствор\", а не как \"гомогенизация\", если в исходнике нет слова \"homogenization\".\n"
        "7. Не объединяй эту страницу с другими страницами.\n"
        "8. Если часть текста повреждена или непонятна, сохрани максимально близкий смысл без выдумывания.\n"
        "9. Удали/не воспроизводи технические артефакты парсера: [Formula candidate], [Table candidate], cid:123, (cid:123), <latexit>, приватные/битые glyph-символы, □ и �. Удаляй только сам служебный маркер, но не удаляй и не оставляй непереведённым содержательный текст рядом с ним. Например, строку \"[Formula candidate] creep strain rate = Aσ^n exp(-Q/RT)\" нужно вернуть как \"Скорость ползучей деформации = Aσ^n exp(-Q/RT)\".\n"
        "10. Если исходная таблица повреждена, сохрани её как читаемый Markdown без выдумывания недостающих значений.\n"
        "11. Не оставляй английские смысловые фразы непереведёнными. Переводи подписи параметров, названия физических величин, подписи к формулам, подписи к таблицам, \"Patent reference\", \"Figure\", \"Table\", \"Discussion\", \"Conclusions\" и похожие текстовые элементы. Не переводятся только формулы, химические обозначения, DOI, URL, патентные номера, марки сплавов и библиографические идентификаторы.\n"
        "12. Если строка содержит формулу или выражение вида \"parameter name = formula\", переведи только название параметра, а математическую часть оставь без искажений. Например: \"γ′ volume fraction = 0.42 ± 0.03\" → \"Объёмная доля γ′-фазы = 0,42 ± 0,03\".\n"
        "13. Сохраняй числовые значения и единицы измерения. Допускается русская запись десятичных дробей через запятую, если остальная страница переведена на русский язык.\n"
        "14. Не исправляй и не дополняй повреждённые данные таблиц, формул, DOI, патентных номеров и ссылок. Если значение отсутствует, оставь прочерк или пустую ячейку как в исходнике.\n"
        "15. Не продолжай документ после последней строки входного Markdown-файла. Если входной файл обрывается на середине предложения, переведи только имеющийся фрагмент и не дописывай продолжение.\n"
        "16. Не добавляй формулы, номера формул, разделы, абзацы или ссылки, которых нет во входном Markdown-файле. Набор номеров формул \tag{...} в переводе не должен содержать новых номеров, отсутствующих во входном тексте.\n\n"
        f"Название статьи: {paper_title or 'без названия'}\n"
        f"Диапазон страниц: {page_label}\n\n"
        "Ответ: только чистый переведённый Markdown, без code fence и без служебных комментариев."
    )
